export const UI: Record<UiLang, Record<UiKey, string>> = { en, id };

/** t('id', 'council.trust', { name: 'Mira' }) → "Percayai Mira" */
export function t(lang: UiLang, key: UiKey, vars?: Record<string, string | number>): string {
  let s = UI[lang][key] ?? UI.en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Before a story exists: user setting → browser language → English. */
export function detectUiLang(saved?: string | null, navigatorLanguage?: string): UiLang {
  if (saved === 'id' || saved === 'en') return saved;
  return navigatorLanguage?.toLowerCase().startsWith('id') ? 'id' : 'en';
}
